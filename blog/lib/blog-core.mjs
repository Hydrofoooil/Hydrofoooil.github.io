// Shared blog renderer. The in-browser editor (/blog/write/) and the local build
// (scripts/build_blog.mjs) both call buildBlog(), so a post published from the browser is
// byte-for-byte what the local build would write. Pure functions: no DOM, no Node APIs.
//
// A post is blog/<slug>/index.md: front matter, then Markdown (GitHub-flavoured, via marked).
//   ---
//   title: My first post          # required
//   date: 2026-11-03              # required, YYYY-MM-DD
//   summary: One-line summary.    # optional; defaults to the first paragraph
//   tags: [robotics, notes]       # optional
//   lang: en                      # optional; e.g. zh-CN for a Chinese post (default en)
//   draft: false                  # optional; true keeps the post unpublished
//   ---
import { Marked } from './vendor/marked.esm.js';

export const SITE = 'https://hydrofoooil.github.io';
export const AUTHOR = 'Ting Mao';
export const MARKER = '<!-- generated by blog/lib/blog-core.mjs; edit index.md and rebuild, not this file -->';
export const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
/** Folders under blog/ that are not posts. */
export const RESERVED_SLUGS = new Set(['lib', 'write']);
export const FRONT_MATTER_KEYS = ['title', 'date', 'summary', 'tags', 'lang', 'draft'];

export class PostError extends Error {}

const marked = new Marked({ gfm: true, breaks: false });

// ---------------------------------------------------------------- front matter

function stripComment(line) {
  let quote = '';
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quote) {
      if (ch === '\\' && quote === '"') i++;
      else if (ch === quote) quote = '';
    } else if (ch === '"' || ch === "'") quote = ch;
    else if (ch === '#' && (i === 0 || /\s/.test(line[i - 1]))) return line.slice(0, i);
  }
  return line;
}

function splitList(inner) {
  const items = [];
  let quote = '', current = '';
  for (let i = 0; i < inner.length; i++) {
    const ch = inner[i];
    if (quote) {
      current += ch;
      if (ch === '\\' && quote === '"') current += inner[++i] ?? '';
      else if (ch === quote) quote = '';
    } else if (ch === '"' || ch === "'") { quote = ch; current += ch; }
    else if (ch === ',') { items.push(current); current = ''; }
    else current += ch;
  }
  items.push(current);
  return items.map(item => item.trim()).filter(Boolean);
}

function parseValue(raw) {
  const value = raw.trim();
  if (value.startsWith('"') && value.endsWith('"') && value.length >= 2) {
    try { return JSON.parse(value); } catch { throw new PostError(`cannot read quoted value ${value}`); }
  }
  if (value.startsWith("'") && value.endsWith("'") && value.length >= 2) return value.slice(1, -1).replace(/''/g, "'");
  if (value.startsWith('[') && value.endsWith(']')) return splitList(value.slice(1, -1)).map(parseValue);
  return value;
}

/** Split index.md into { meta, body }. Supports the simple YAML used by posts: key: value,
 *  quoted strings, [a, b] lists and # comments. Values stay strings (draft: true is read by
 *  readPost), so an unquoted title such as No is never turned into a boolean. */
export function parseFrontMatter(source) {
  const text = source.replace(/^﻿/, '');
  const match = /^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/.exec(text);
  if (!match) throw new PostError('missing front matter (--- ... ---) at the top');
  const meta = {};
  for (const raw of match[1].split(/\r?\n/)) {
    const line = stripComment(raw);
    if (!line.trim()) continue;
    const pair = /^([A-Za-z_][\w-]*)\s*:(.*)$/.exec(line.trim());
    if (!pair) throw new PostError(`cannot read front matter line: ${raw.trim()}`);
    meta[pair[1]] = parseValue(pair[2]);
  }
  return { meta, body: text.slice(match[0].length) };
}

function quoteIfNeeded(value) {
  const text = String(value);
  const plain = text === text.trim() && text !== '' && !/^[\[\]{}"'&*!|>%@`#,-]/.test(text)
    && !/[:#]\s|:$|\s#/.test(text) && !/^(true|false|yes|no|null|~)$/i.test(text) && !/[\r\n]/.test(text);
  return plain ? text : JSON.stringify(text);
}

/** Inverse of parseFrontMatter: write index.md from fields and the Markdown body. */
export function serializePost(meta, body) {
  const lines = ['---'];
  for (const key of FRONT_MATTER_KEYS) {
    const value = meta[key];
    if (value === undefined || value === null || value === '' || (Array.isArray(value) && !value.length)) continue;
    if (key === 'draft') { if (value) lines.push('draft: true'); continue; }
    if (key === 'tags') lines.push(`tags: [${value.map(tag => (/[,\[\]]/.test(tag) ? JSON.stringify(String(tag)) : quoteIfNeeded(tag))).join(', ')}]`);
    else lines.push(`${key}: ${quoteIfNeeded(value)}`);
  }
  lines.push('---', '');
  return lines.join('\n') + String(body).replace(/^\s*\n/, '').replace(/\s*$/, '\n');
}

// ---------------------------------------------------------------- posts

/** Lowercase ASCII slug from a title ('' when the title has no ASCII letters or digits). */
export function slugify(title) {
  return String(title).normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 64).replace(/-+$/, '');
}

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
function unescapeHtml(text) {
  return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, name) => {
    if (name[0] === '#') return String.fromCodePoint(name[1].toLowerCase() === 'x' ? parseInt(name.slice(2), 16) : parseInt(name.slice(1), 10));
    return ENTITIES[name.toLowerCase()] ?? whole;
  });
}

export function esc(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#x27;');
}

function validDate(value) {
  const text = value instanceof Date ? value.toISOString().slice(0, 10) : String(value ?? '').trim();
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(text);
  if (!match) return '';
  const date = new Date(Date.UTC(+match[1], +match[2] - 1, +match[3]));
  return date.toISOString().slice(0, 10) === text ? text : '';
}

/** Parse and render one post. Returns null for a draft; throws PostError when invalid. */
export function readPost(slug, source) {
  const { meta, body: markdown } = parseFrontMatter(source);
  if (meta.draft === true || /^(true|yes)$/i.test(String(meta.draft ?? ''))) return null;
  if (!SLUG_PATTERN.test(slug) || RESERVED_SLUGS.has(slug)) {
    throw new PostError(`blog/${slug}: the folder name is the URL; use lowercase letters, digits and hyphens (not ${[...RESERVED_SLUGS].join(' or ')})`);
  }
  const title = typeof meta.title === 'string' ? meta.title.trim() : '';
  if (!title) throw new PostError(`blog/${slug}: front matter needs a title`);
  const date = validDate(meta.date);
  if (!date) throw new PostError(`blog/${slug}: front matter needs date: YYYY-MM-DD`);
  let tags = meta.tags ?? [];
  if (typeof tags === 'string') tags = tags.split(',');
  tags = tags.map(tag => String(tag).trim()).filter(Boolean);
  const body = marked.parse(markdown);
  let summary = typeof meta.summary === 'string' ? meta.summary.trim() : '';
  if (!summary) {
    const first = /<p>([\s\S]*?)<\/p>/.exec(body);
    summary = first ? unescapeHtml(first[1].replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim() : '';
    if ([...summary].length > 180) summary = [...summary].slice(0, 177).join('').trimEnd() + '…';
  }
  const plain = unescapeHtml(body.replace(/<[^>]+>/g, ' '));
  const cjk = (plain.match(/[㐀-鿿豈-﫿]/g) || []).length;
  const words = (plain.match(/[A-Za-z0-9]+(?:['’-][A-Za-z0-9]+)*/g) || []).length;
  return {
    slug, title, date, summary, tags,
    lang: String(meta.lang || 'en'),
    body,
    minutes: Math.max(1, Math.round(words / 230 + cjk / 400)),
    url: `/blog/${slug}/`,
  };
}

// ---------------------------------------------------------------- pages

const shownDate = date => date.replace(/-/g, '.');

function page({ lang, title, description, path, ogType, cssVersion, year, activeList, main }) {
  const current = activeList ? ' aria-current="page"' : '';
  return `<!doctype html>
${MARKER}
<html lang="${esc(lang)}">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${esc(title)}</title>
    <meta name="description" content="${esc(description)}">
    <meta name="theme-color" content="#fafbf8">
    <link rel="canonical" href="${SITE}${path}">
    <meta property="og:type" content="${ogType}">
    <meta property="og:title" content="${esc(title)}">
    <meta property="og:description" content="${esc(description)}">
    <meta property="og:url" content="${SITE}${path}">
    <link rel="icon" href="/favicon.ico" sizes="16x16 32x32 48x48">
    <link rel="icon" type="image/png" href="/assets/github-avatar.png" sizes="192x192">
    <link rel="alternate" type="application/atom+xml" title="${AUTHOR} · Blog" href="/blog/feed.xml">
    <link rel="stylesheet" href="/blog/blog.css?v=${cssVersion}">${ogType === 'article' ? '\n    <script src="/blog/lib/edit-link.js" defer></script>' : ''}
  </head>
  <body>
    <header class="blog-bar">
      <a class="blog-home" href="/" lang="en">${AUTHOR}</a>
      <nav class="blog-nav" aria-label="Site" lang="en">
        <a href="/">Home</a>
        <a class="is-active" href="/blog/"${current}>Blog</a>
      </nav>
    </header>
    <main class="blog-main">
${main}
    </main>
    <footer class="blog-footer" lang="en">© ${year} ${AUTHOR} · <a href="/blog/feed.xml">Atom feed</a></footer>
  </body>
</html>
`;
}

function tagList(tags) {
  if (!tags.length) return '';
  return '<ul class="post-tags" aria-label="Tags">' + tags.map(tag => `<li>${esc(tag)}</li>`).join('') + '</ul>';
}

/** The full HTML page for one post (as returned by readPost). */
export function renderPost(post, { cssVersion, year }) {
  const main = `      <article class="post">
        <a class="post-back" href="/blog/" lang="en">← All posts</a>
        <h1 class="post-title">${esc(post.title)}</h1>
        <div class="post-meta" lang="en"><time datetime="${post.date}">${shownDate(post.date)}</time><span aria-hidden="true">·</span><span>${post.minutes} min read</span><a class="post-edit" href="/blog/write/?edit=${post.slug}" hidden>✎ Edit</a></div>
        ${tagList(post.tags)}
        <div class="post-body">
${post.body}
        </div>
      </article>`;
  return page({ lang: post.lang, title: `${post.title} · ${AUTHOR}`, description: post.summary || post.title,
    path: post.url, ogType: 'article', cssVersion, year, activeList: false, main });
}

/** The post list at /blog/ (posts newest first). */
export function renderIndex(posts, { cssVersion, year }) {
  let listing;
  if (posts.length) {
    const items = posts.map(post => `        <li class="post-item" lang="${esc(post.lang)}">
          <time class="post-item-date" datetime="${post.date}" lang="en">${shownDate(post.date)}</time>
          <div class="post-item-text">
            <h2><a href="${post.url}">${esc(post.title)}</a></h2>
            ${post.summary ? `<p>${esc(post.summary)}</p>` : ''}
            ${tagList(post.tags)}
          </div>
        </li>`).join('\n');
    listing = `      <ol class="post-list" reversed>\n${items}\n      </ol>`;
  } else {
    listing = '      <p class="blog-empty">No posts yet. Check back soon.</p>';
  }
  const main = `      <h1 class="blog-title">Blog</h1>\n${listing}`;
  return page({ lang: 'en', title: `Blog · ${AUTHOR}`, description: `Blog posts by ${AUTHOR}.`, path: '/blog/',
    ogType: 'website', cssVersion, year, activeList: true, main });
}

/** Atom feed with the full text of every post. */
export function renderFeed(posts) {
  const stamp = date => `${date}T00:00:00Z`;
  const updated = posts.reduce((latest, post) => (post.date > latest ? post.date : latest), '2026-11-03');
  const entries = posts.map(post => `  <entry>
    <title>${esc(post.title)}</title>
    <link href="${SITE}${post.url}"/>
    <id>${SITE}${post.url}</id>
    <updated>${stamp(post.date)}</updated>
    <summary>${esc(post.summary)}</summary>
    <content type="html">${esc(post.body)}</content>
  </entry>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>${AUTHOR} · Blog</title>
  <link href="${SITE}/blog/"/>
  <link rel="self" href="${SITE}/blog/feed.xml"/>
  <id>${SITE}/blog/</id>
  <updated>${stamp(updated)}</updated>
  <author><name>${AUTHOR}</name></author>
${entries ? entries + '\n' : ''}</feed>
`;
}

/**
 * Build the whole blog from every post's index.md.
 * @param {{slug: string, source: string}[]} sources  one entry per blog/<slug>/index.md
 * @param {{cssVersion: string, year?: number}} options  cssVersion: first 8 hex of SHA-1(blog/blog.css)
 * @returns {{files: Record<string, string>, posts: object[], unpublished: string[], errors: string[]}}
 *   files: repo path -> content for every generated file (blog/index.html, blog/feed.xml and
 *   blog/<slug>/index.html per published post); unpublished: slugs that are drafts, whose old
 *   blog/<slug>/index.html should be removed; errors: invalid posts (nothing is written for them).
 */
export function buildBlog(sources, { cssVersion, year = new Date().getFullYear() }) {
  const posts = [], unpublished = [], errors = [], files = {};
  for (const { slug, source } of sources) {
    try {
      const post = readPost(slug, source);
      if (post) posts.push(post);
      else unpublished.push(slug);
    } catch (error) {
      if (!(error instanceof PostError)) throw error;
      errors.push(error.message.startsWith('blog/') ? error.message : `blog/${slug}: ${error.message}`);
    }
  }
  posts.sort((a, b) => (a.date === b.date ? (a.title < b.title ? 1 : -1) : a.date < b.date ? 1 : -1));
  for (const post of posts) files[`blog/${post.slug}/index.html`] = renderPost(post, { cssVersion, year });
  files['blog/index.html'] = renderIndex(posts, { cssVersion, year });
  files['blog/feed.xml'] = renderFeed(posts);
  return { files, posts, unpublished, errors };
}
