#!/usr/bin/env python3
"""Build the static blog under blog/ from Markdown.

Each post is a folder blog/<slug>/ holding index.md (front matter + Markdown) and any
images it uses (link them with relative paths, e.g. ![](figure.png)). This script writes
blog/<slug>/index.html next to the source, the post list at blog/index.html and an Atom
feed at blog/feed.xml. Posts marked `draft: true` are skipped, and their stale output is
removed. Run from anywhere:

    /usr/bin/python3 scripts/build_blog.py

Front matter:

    ---
    title: My first post          # required
    date: 2026-11-03              # required, YYYY-MM-DD
    summary: One-line summary.    # optional; defaults to the first paragraph
    tags: [robotics, notes]       # optional
    lang: en                      # optional; e.g. zh-CN for a Chinese post (default en)
    draft: false                  # optional; true keeps the post unpublished
    ---
"""
from __future__ import annotations

import datetime as dt
import hashlib
import html
import re
import sys
from pathlib import Path

import markdown
import yaml

ROOT = Path(__file__).resolve().parent.parent
BLOG = ROOT / 'blog'
SITE = 'https://hydrofoooil.github.io'
AUTHOR = 'Ting Mao'
MARKER = '<!-- generated by scripts/build_blog.py; edit index.md and rebuild, not this file -->'
SLUG = re.compile(r'[a-z0-9]+(?:-[a-z0-9]+)*')
MARKDOWN_EXTENSIONS = ['extra', 'toc', 'sane_lists', 'smarty']


class PostError(ValueError):
    pass


def read_post(folder: Path) -> dict | None:
    source = folder / 'index.md'
    text = source.read_text(encoding='utf-8')
    match = re.match(r'---\s*\n(.*?)\n---\s*\n', text, flags=re.S)
    if not match:
        raise PostError(f'{source}: missing front matter (--- ... ---) at the top')
    meta = yaml.safe_load(match[1]) or {}
    if not isinstance(meta, dict):
        raise PostError(f'{source}: front matter must be key: value pairs')
    if meta.get('draft'):
        return None
    if not SLUG.fullmatch(folder.name):
        raise PostError(f'{folder}: folder name is the URL; use lowercase letters, digits and hyphens')
    title = meta.get('title')
    if not isinstance(title, str) or not title.strip():
        raise PostError(f'{source}: front matter needs a title')
    date = meta.get('date')
    if isinstance(date, dt.datetime):
        date = date.date()
    if isinstance(date, str):
        try:
            date = dt.date.fromisoformat(date)
        except ValueError:
            date = None
    if not isinstance(date, dt.date):
        raise PostError(f'{source}: front matter needs date: YYYY-MM-DD')
    tags = meta.get('tags') or []
    if isinstance(tags, str):
        tags = [tag.strip() for tag in tags.split(',') if tag.strip()]
    converter = markdown.Markdown(extensions=MARKDOWN_EXTENSIONS)
    body = converter.convert(text[match.end():])
    summary = meta.get('summary')
    if not summary:
        first = re.search(r'<p>(.*?)</p>', body, flags=re.S)
        summary = html.unescape(re.sub(r'<[^>]+>', '', first[1])).strip() if first else ''
        if len(summary) > 180:
            summary = summary[:177].rstrip() + '…'
    plain = html.unescape(re.sub(r'<[^>]+>', ' ', body))
    cjk = len(re.findall(r'[㐀-鿿豈-﫿]', plain))
    words = len(re.findall(r'[A-Za-z0-9]+(?:[\'’-][A-Za-z0-9]+)*', plain))
    return {
        'slug': folder.name,
        'title': title.strip(),
        'date': date,
        'summary': str(summary).strip(),
        'tags': [str(tag) for tag in tags],
        'lang': str(meta.get('lang') or 'en'),
        'body': body,
        'minutes': max(1, round(words / 230 + cjk / 400)),
        'url': f'/blog/{folder.name}/',
    }


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def shown_date(date: dt.date) -> str:
    return date.strftime('%Y.%m.%d')


def page(*, lang: str, title: str, description: str, path: str, og_type: str, css: str, active_list: bool, main: str) -> str:
    current = ' aria-current="page"' if active_list else ''
    return f'''<!doctype html>
{MARKER}
<html lang="{esc(lang)}">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{esc(title)}</title>
    <meta name="description" content="{esc(description)}">
    <meta name="theme-color" content="#fafbf8">
    <link rel="canonical" href="{SITE}{path}">
    <meta property="og:type" content="{og_type}">
    <meta property="og:title" content="{esc(title)}">
    <meta property="og:description" content="{esc(description)}">
    <meta property="og:url" content="{SITE}{path}">
    <link rel="icon" href="/favicon.ico" sizes="16x16 32x32 48x48">
    <link rel="icon" type="image/png" href="/assets/github-avatar.png" sizes="192x192">
    <link rel="alternate" type="application/atom+xml" title="{AUTHOR} · Blog" href="/blog/feed.xml">
    <link rel="stylesheet" href="/blog/blog.css?v={css}">
  </head>
  <body>
    <header class="blog-bar">
      <a class="blog-home" href="/" lang="en">{AUTHOR}</a>
      <nav class="blog-nav" aria-label="Site" lang="en">
        <a href="/">Home</a>
        <a class="is-active" href="/blog/"{current}>Blog</a>
      </nav>
    </header>
    <main class="blog-main">
{main}
    </main>
    <footer class="blog-footer" lang="en">© {dt.date.today().year} {AUTHOR} · <a href="/blog/feed.xml">Atom feed</a></footer>
  </body>
</html>
'''


def tag_list(tags: list[str]) -> str:
    if not tags:
        return ''
    return '<ul class="post-tags" aria-label="Tags">' + ''.join(f'<li>{esc(tag)}</li>' for tag in tags) + '</ul>'


def post_page(post: dict, css: str) -> str:
    main = f'''      <article class="post">
        <a class="post-back" href="/blog/" lang="en">← All posts</a>
        <h1 class="post-title">{esc(post['title'])}</h1>
        <div class="post-meta" lang="en"><time datetime="{post['date'].isoformat()}">{shown_date(post['date'])}</time><span aria-hidden="true">·</span><span>{post['minutes']} min read</span></div>
        {tag_list(post['tags'])}
        <div class="post-body">
{post['body']}
        </div>
      </article>'''
    return page(lang=post['lang'], title=f"{post['title']} · {AUTHOR}", description=post['summary'] or post['title'],
                path=post['url'], og_type='article', css=css, active_list=False, main=main)


def index_page(posts: list[dict], css: str) -> str:
    if posts:
        items = '\n'.join(f'''        <li class="post-item" lang="{esc(post['lang'])}">
          <time class="post-item-date" datetime="{post['date'].isoformat()}" lang="en">{shown_date(post['date'])}</time>
          <div class="post-item-text">
            <h2><a href="{post['url']}">{esc(post['title'])}</a></h2>
            {f"<p>{esc(post['summary'])}</p>" if post['summary'] else ''}
            {tag_list(post['tags'])}
          </div>
        </li>''' for post in posts)
        listing = f'      <ol class="post-list" reversed>\n{items}\n      </ol>'
    else:
        listing = '      <p class="blog-empty">No posts yet. Check back soon.</p>'
    main = f'      <h1 class="blog-title">Blog</h1>\n{listing}'
    return page(lang='en', title=f'Blog · {AUTHOR}', description=f'Blog posts by {AUTHOR}.', path='/blog/',
                og_type='website', css=css, active_list=True, main=main)


def feed(posts: list[dict]) -> str:
    updated = max((post['date'] for post in posts), default=dt.date(2026, 11, 3))
    stamp = lambda date: f'{date.isoformat()}T00:00:00Z'
    entries = '\n'.join(f'''  <entry>
    <title>{esc(post['title'])}</title>
    <link href="{SITE}{post['url']}"/>
    <id>{SITE}{post['url']}</id>
    <updated>{stamp(post['date'])}</updated>
    <summary>{esc(post['summary'])}</summary>
    <content type="html">{esc(post['body'])}</content>
  </entry>''' for post in posts)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>{AUTHOR} · Blog</title>
  <link href="{SITE}/blog/"/>
  <link rel="self" href="{SITE}/blog/feed.xml"/>
  <id>{SITE}/blog/</id>
  <updated>{stamp(updated)}</updated>
  <author><name>{AUTHOR}</name></author>
{entries}
</feed>
'''


def write(path: Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding='utf-8') != text:
        path.write_text(text, encoding='utf-8')
        print('wrote', path.relative_to(ROOT))


def main() -> int:
    css = hashlib.sha1((BLOG / 'blog.css').read_bytes()).hexdigest()[:8]
    posts, errors = [], []
    folders = sorted(path for path in BLOG.iterdir() if path.is_dir() and not path.name.startswith(('.', '_')))
    for folder in folders:
        output = folder / 'index.html'
        post = None
        if (folder / 'index.md').exists():
            try:
                post = read_post(folder)
            except PostError as error:
                errors.append(str(error))
                continue
        if post:
            posts.append(post)
            write(output, post_page(post, css))
        elif output.exists() and MARKER in output.read_text(encoding='utf-8'):
            output.unlink()  # draft or deleted post: take its old page down
            print('removed', output.relative_to(ROOT))
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    posts.sort(key=lambda post: (post['date'], post['title']), reverse=True)
    write(BLOG / 'index.html', index_page(posts, css))
    write(BLOG / 'feed.xml', feed(posts))
    print(f'{len(posts)} post(s) published')
    return 0


if __name__ == '__main__':
    sys.exit(main())
